// tools/rom909.mjs — our own hi-hat, crash and ride sounds for the TR-909's 6-bit ROM playback path (IMPL-7c §2.4, lane R9).
// The 909 played short recordings of real cymbals from three 32K-word chips; those are someone else's audio and are never
// used, fetched, analysed or compared here (IMPL-7c D4). These are ours: modal models of struck thin plates — a pair of
// 14-inch hi-hat plates struck slightly open and clamped shut, an 18-inch thin crash, a 20-inch ride — recorded the way a
// sampler of 1983 would have: rendered at 192 kHz, band-limited below the word clock's Nyquist, resampled to 30 kHz,
// pre-compensated for the playback's own envelopes (the hats compressed, the cymbals divided by the address staircase), each
// sound normalised with 1 dB of headroom, ended at mid-scale, quantised to 6 bits (round to nearest, no dither: the grain is
// the point). The images live in dr-808.js between the ROM909 markers, one character per word (the format: IMPL-7c §14 lane R9).
//   node tools/rom909.mjs              build, print each sound's statistics and whether dr-808.js's block is current
//   node tools/rom909.mjs --write      rewrite the lines between the markers (the lead, after merging lanes V9 and R9)
//   node tools/rom909.mjs --check      exit 1 unless the block equals a fresh build (a missing frame fails too)
//   node tools/rom909.mjs --block      print the generated lines (what --write puts between the markers)

// ---------------------------------------------------------------- the plate renderer
function modesOf(pl, rnd) {
  const out = [];
  for (let k = 0; ; k++) {
    const f = pl.f0 + (k + rnd()) / pl.dens;
    if (f > 20000) break;
    out.push({ f, a: gauss(rnd), cr: gauss(rnd), ci: gauss(rnd) });
  }
  return out;
}
// the stick's force pulse at FS: t e^(−t/θ), unit sum, to 30 θ
function pulseOf(theta) {
  const n = Math.ceil(30 * theta * FS), p = new Float64Array(n), q = expD(-1 / (theta * FS));
  let e = 1, s = 0;
  for (let i = 0; i < n; i++) { p[i] = i * e; s += p[i]; e *= q; }
  for (let i = 0; i < n; i++) p[i] /= s;
  return p;
}
// the amplitude tilt: (f / 1 kHz)^β above a second-order low cut fl, a first-order roll-off above fh (if any)
function tiltOf(t, f) {
  let T = powD(f / 1000, t.beta) * (f * f / (f * f + t.fl * t.fl));
  if (t.fh) T /= 1 + (f / t.fh) * (f / t.fh);
  return T;
}
function sigOf(S, f) {
  const k = f / 1000;
  let s = S.sig[0] + S.sig[1] * k + S.sig[2] * k * k;
  if (S.sigLow) s += S.sigLow[0] * (S.sigLow[1] / f) * (S.sigLow[1] / f);   // the clamp's extra loss on the low modes
  return s;
}
// a damped resonator y = c1 y₋₁ − c2 y₋₂ + g p[n] from the state (y1, y2), samples [0, nEnd) of bus
function ring(bus, nEnd, c1, c2, y1, y2, g, pulse) {
  const P = Math.min(pulse.length, nEnd);
  let n = 0;
  for (; n < P; n++) { const y = c1 * y1 - c2 * y2 + g * pulse[n]; bus[n] += y; y2 = y1; y1 = y; }
  for (; n < nEnd; n++) { const y = c1 * y1 - c2 * y2; bus[n] += y; y2 = y1; y1 = y; }
}
// one mode, three resonators on its frequency: the ring (decay σ: the mode as it sounds on), the move (σ + 1/ρ: a low mode's
// strike energy draining into the cascade, a high mode's cascade arriving) and the tick (σ + 1/τt: the stick's contact
// transient). The strike's pulse drives each (gains As, Af, At: causal); the cascade phasor P = pr + i pi starts the ring as
// Im{P rⁿ e^{iωn}} and the move as its negative, so the arriving energy rises from 0 over ρ; into bus[0…N)
function mode(bus, N, f, sigma, rho, As, Af, At, taut, pulse, pr, pi) {
  const w = TAU * f / FS, c = cosD(w), s = sinD(w), c2w = 2 * c * c - 1, s2w = 2 * s * c;
  const ie = Math.abs(pr) + Math.abs(pi), y1 = pi * c - pr * s, y2 = pi * c2w - pr * s2w;   // Im{P e^{−iω}}, Im{P e^{−2iω}}
  const end = (M, sg) => M > 0 ? Math.min(N, Math.ceil(FS * logD(M / 1e-9) / sg)) : 0;
  const r = expD(-sigma / FS);
  ring(bus, end(Math.abs(As) + 2 * ie, sigma), 2 * r * c, r * r, y1 / r, y2 / (r * r), As * s, pulse);
  if (rho > 0 && (Af !== 0 || ie > 0)) {
    const sg = sigma + 1 / rho, rb = expD(-sg / FS);
    ring(bus, end(Math.abs(Af) + 2 * ie, sg), 2 * rb * c, rb * rb, -y1 / rb, -y2 / (rb * rb), Af * s, pulse);
  }
  if (At !== 0) {
    const sg = sigma + 1 / taut, rt = expD(-sg / FS);
    ring(bus, end(Math.abs(At), sg), 2 * rt * c, rt * rt, 0, 0, At * s, pulse);
  }
}
// a resonator driven for its whole length by e (the chatter), from rest
function driven(bus, N, f, sigma, g, e) {
  const w = TAU * f / FS, r = expD(-sigma / FS), c1 = 2 * r * cosD(w), c2 = r * r, gs = g * sinD(w);
  let y1 = 0, y2 = 0;
  for (let n = 0; n < N; n++) { const y = c1 * y1 - c2 * y2 + gs * e[n]; bus[n] += y; y2 = y1; y1 = y; }
}
// a slow random pressure: Gaussian values held for `hold` s through two one-poles at fc, unit RMS over n samples
function slowRandom(n, hold, fc, rnd) {
  const h = Math.round(hold * FS), a = expD(-TAU * fc / FS), m = new Float64Array(n);
  let u = 0, z1 = 0, z2 = 0, ss = 0;
  for (let i = 0; i < n; i++) {
    if (i % h === 0) u = gauss(rnd);
    z1 = a * z1 + (1 - a) * u; z2 = a * z2 + (1 - a) * z1; m[i] = z2; ss += z2 * z2;
  }
  const k = 1 / Math.max(1e-30, sqrtD(ss / n));
  for (let i = 0; i < n; i++) m[i] *= k;
  return m;
}
// the open hat's chatter (its sizzle): the top plate's rim tapping the bottom one after the strike — impacts at a random
// rate (each a one-sample impulse, a Gaussian strength), the strength falling with τ, ramping in over `onset` as the plates
// part, and swelling with the contact's slow random pressure (depth about 1)
function chatterOf(Z, n, rnd) {
  const m = slowRandom(n, Z.hold, Z.fc, rnd), e = new Float64Array(n), p = Z.rate / FS, a = expD(-1 / (Z.tau * FS));
  const ra = Math.round(Z.onset * FS);
  let env = 1;
  for (let i = 0; i < n; i++) {
    env *= a;
    if (rnd() < p) e[i] = gauss(rnd) * env * Math.max(0, 1 + Z.depth * m[i]) * (i < ra ? i / ra : 1);
  }
  return e;
}
// a sound at FS, n samples: every plate's modes struck, the bell's partials (ride), the chatter through the upper modes (OH)
export function renderSound(name, n) {
  const S = SOUNDS[name], rnd = rng(name), pulse = pulseOf(S.theta), shift = S.shift || 1, C = S.casc, K = S.tick;
  const bus = new Float64Array(n), plates = PLATES[S.plates], prand = rng(S.plates), Z = S.chatter;
  const ch = Z ? chatterOf(Z, n, rng(name + '-chatter')) : null;
  for (const pl of plates) {
    for (const m of modesOf(pl, prand)) {
      const pr = gauss(rnd), pi = gauss(rnd);                  // this hit's cascade phase (drawn for every mode: a fixed order)
      const f = m.f * shift;
      if (f > F_TOP) continue;
      const T = tiltOf(S.tilt, f), k = f / C.fc, wc = k * k / (1 + k * k) / (C.fh ? 1 + (f / C.fh) * (f / C.fh) : 1);
      const q = C.drain / (1 + k * k), qt = K ? K.q : 0, A = m.a * T, P = C.g * T * wc * 0.5, sg = sigOf(S, f);
      mode(bus, n, f, sg, C.rho1k * powD(f / 1000, C.gamma), A * (1 - q - qt), A * q,
        T * qt * (K && K.coh ? K.coh + (1 - K.coh) * m.a : m.a), K ? K.tau : 0, pulse, P * (m.cr + pr), P * (m.ci + pi));
      if (ch && f >= Z.fx) driven(bus, n, f, sg, A * Z.g, ch);
    }
  }
  if (S.bell) {                                                // the bell: few, strong, long partials, each a split pair
    const B = S.bell;
    for (let j = 0; j < B.ratios.length; j++) {
      const f = B.f * B.ratios[j], sg = 1 / B.tau[j], A = B.gain * B.amp[j] * (gauss(rnd) < 0 ? -1 : 1);
      mode(bus, n, f, sg, 0, A * 0.6, 0, 0, 0, pulse, 0, 0);
      mode(bus, n, f + B.split * (1 + j * 0.35), sg * 1.15, 0, A * 0.4, 0, 0, 0, pulse, 0, 0);
    }
  }
  return bus;
}
// √x by Newton from a power-of-two start (exact ops; deterministic, ≤ 1 ulp off)
export function sqrtD(x) {
  if (!(x > 0)) return 0;
  let y = 1, m = x;
  while (m >= 4) { m *= 0.25; y *= 2; }
  while (m < 0.25) { m *= 4; y *= 0.5; }
  for (let j = 0; j < 8; j++) y = 0.5 * (y + x / y);
  return y;
}

// ---------------------------------------------------------------- the sampler: band-limit + resample 192 kHz → 30 kHz
// a Kaiser-windowed sinc (cut 14 kHz, ±1 kHz transition, ≈ 70 dB), 5 polyphase rows (192 / 30 = 32 / 5), each row's DC gain 1
const AA = { fc: 14000, H: 207, beta: 6.76 };
function i0sq(x2) { let t = 1, s = 1; for (let k = 1; k < 40; k++) { t *= x2 / (4 * k * k); s += t; } return s; }  // I0(√x2)
let KER = null;
function kernel() {
  if (KER) return KER;
  const { fc, H, beta } = AA, b = 2 * fc / FS, i0b = i0sq(beta * beta), rows = [];
  for (let ph = 0; ph < 5; ph++) {
    const fr = ph / 5, row = new Float64Array(2 * H + 2);
    let s = 0;
    for (let m = -H; m <= H + 1; m++) {
      const t = fr - m, u = t / (H + 1);
      const sn = t === 0 ? b : sinD(PI * b * t) / (PI * t);
      const w = Math.abs(u) < 1 ? i0sq(beta * beta * (1 - u * u)) / i0b : 0;
      row[m + H] = sn * w; s += sn * w;
    }
    for (let i = 0; i < row.length; i++) row[i] /= s;
    rows.push(row);
  }
  return (KER = rows);
}
export function sampler(x, words) {
  const rows = kernel(), H = AA.H, y = new Float64Array(words);
  for (let j = 0; j < words; j++) {
    const nc = Math.floor(j * 32 / 5), row = rows[(j * 32) % 5];
    let s = 0;
    for (let m = -H; m <= H + 1; m++) { const i = nc + m; if (i >= 0 && i < x.length) s += x[i] * row[m + H]; }
    y[j] = s;
  }
  return y;
}

// ---------------------------------------------------------------- envelopes, pre-compensation, codes
const WIN = 150;                                 // a 5 ms window at 30 kHz: the level measure
// RMS² in a centred window of w words at each word (prefix sums)
function msOf(y, w = WIN) {
  const n = y.length, ps = new Float64Array(n + 1), out = new Float64Array(n), h = w >> 1;
  for (let i = 0; i < n; i++) ps[i + 1] = ps[i] + y[i] * y[i];
  for (let i = 0; i < n; i++) { const a = Math.max(0, i - h), b = Math.min(n, i + h + 1); out[i] = (ps[b] - ps[a]) / (b - a); }
  return out;
}
// the hats' compression: divide by the falling envelope^α (monotone from its peak: a compressor with a slow release), the gain
// capped at gmax dB — the codes carry the sizzle, the playback's RC envelope the decay (SN9: the hat sounds were compressed)
function compress(y, alpha, gmaxDb) {
  const e = msOf(y), n = y.length, g = new Float64Array(n), cap = dbA(gmaxDb);
  let pk = 0;
  for (let i = 1; i < n; i++) if (e[i] > e[pk]) pk = i;
  for (let i = n - 2; i >= pk; i--) if (e[i + 1] > e[i]) e[i] = e[i + 1];   // running max from the right: monotone
  for (let i = 0; i < n; i++) g[i] = i <= pk || !(e[i] > 0) ? 1 : Math.min(cap, expD(-alpha / 2 * logD(e[i] / e[pk])));
  for (let i = 0; i < n; i++) y[i] *= g[i];
  return y;
}
// the cymbals' pre-compensation: ÷ the staircase's gain at step i >> 9 (relative to step 0), the boost capped at 24 dB
const STAIR_CAP = dbA(24);
function unstair(y, st) { for (let i = 0; i < y.length; i++) y[i] /= Math.max(st[i >> 9], 1 / STAIR_CAP); return y; }
// the region's end: a raised-cosine fade over `sec` to exactly 0 (mid-scale: no DC step when the latch holds the last word)
function fadeEnd(y, sec) {
  const n = y.length, f = Math.round(sec * WORD_HZ);
  for (let j = 0; j < f; j++) y[n - f + j] *= 0.5 * (1 + cosD(PI * (j + 1) / f));
  y[n - 1] = 0;
  return y;
}
export const PEAK_CODE = 31 * dbA(-1);          // ±27.6 LSB about mid-scale 32: 1 dB of headroom
// codes 32 + round(v), v = y · PEAK_CODE / max|y|; returns the codes and v (the margins: how far each v sits from a tie)
function quantise(y) {
  let pk = 0;
  for (let i = 0; i < y.length; i++) pk = Math.max(pk, Math.abs(y[i]));
  const k = PEAK_CODE / pk, c = new Uint8Array(y.length), v = new Float64Array(y.length);
  for (let i = 0; i < y.length; i++) { v[i] = y[i] * k; c[i] = Math.min(63, Math.max(0, 32 + Math.round(v[i]))); }
  return { c, v };
}

// ---------------------------------------------------------------- the model's staircase (ENV9) or the tool's stand-in
// Dr808.proto.tr909.ENV9.cr / .rd: the cymbal VCA's gain at each of the 64 staircase steps (address bits A9–A14), any common
// scale. Until lane V9's model exists the stand-in: the anti-log of a linear ramp, 0.263 dB a step for the crash (−14 dB at
// 0.91 s, R9 §9's scope reading) and that × R432 / R439 (270 k / 470 k) for the ride [C]. Quantised to 2⁻³² relative to step
// 0, so a last-bit difference in the model's own maths cannot reach a code (IMPL-7c §14 lane R9).
export function stairs() {
  const sc = dspScope({ files: ['dr-808.js'] }), D = sc.global('Dr808');
  if (!D) throw new Error('rom909: dr-808.js failed to load (Dr808 null)');
  const P9 = D.proto && D.proto.tr909, has909 = !!(D.mach && D.mach.tr909);
  const E = P9 && P9.ENV9;
  if (has909 || E) {
    const ok = a => a && a.length === 64 && Array.prototype.every.call(a, x => typeof x === 'number' && x > 0 && x < Infinity);
    if (!E || !ok(E.cr) || !ok(E.rd))
      throw new Error('rom909: Dr808.proto.tr909.ENV9.cr / .rd (the 64 staircase gains of each cymbal) missing or malformed — '
        + 'the tool and the model share them (IMPL-7c §2.4, §14 lane R9)');
    return { src: 'model', cr: q32(E.cr), rd: q32(E.rd) };
  }
  const st = d => { const a = new Float64Array(64); for (let k = 0; k < 64; k++) a[k] = dbA(-d * k); return q32(a); };
  return { src: 'stand-in', cr: st(0.263), rd: st(0.263 * 270 / 470) };
}
const Q32 = 4294967296;
function q32(a) { const o = new Float64Array(64); for (let k = 0; k < 64; k++) o[k] = Math.round(a[k] / a[0] * Q32) / Q32; return o; }

// ---------------------------------------------------------------- the build
const RENDER_PAD = 2 * AA.H + 64;                // samples past a region's last word (the filter's half-length and some)
export function region(name, st) {
  const S = SOUNDS[name], words = S.len, x = renderSound(name, Math.ceil(words * 32 / 5) + RENDER_PAD);
  const design = sampler(x, words);              // the sound as designed: what the playback should give back
  const y = Float64Array.from(design);
  if (S.comp !== undefined) compress(y, S.comp, S.gmax);
  else unstair(y, st);
  fadeEnd(y, S.fade);
  if (S.comp === undefined) fadeEnd(design, S.fade);
  return { design, y, ...quantise(y) };
}
export function build(opt = {}) {
  const st = opt.stairs || stairs();
  const oh = region('oh', null), ch = region('ch', null), cr = region('cr', st.cr), rd = region('rd', st.rd);
  const hh = new Uint8Array(N_IMG);
  hh.set(oh.c, 0); hh.set(ch.c, OPEN_N);
  return { hh, cr: cr.c, rd: rd.c, env: st.src, stairs: st, parts: { oh, ch, cr, rd } };
}

// ---------------------------------------------------------------- the block (IMPL-7c §14 lane R9: the format)
export const encode = codes => { let s = ''; for (let i = 0; i < codes.length; i++) s += ALPHABET[codes[i]]; return s; };
export function decode(s) {
  const t = new Int16Array(128).fill(-1), o = new Uint8Array(s.length);
  for (let i = 0; i < 64; i++) t[ALPHABET.charCodeAt(i)] = i;
  for (let i = 0; i < s.length; i++) { const c = s.charCodeAt(i), v = c < 128 ? t[c] : -1; if (v < 0) throw new Error('rom909: not a code'); o[i] = v; }
  return o;
}
export const hashes = B => ({ hh: fnv1a32(encode(B.hh)), cr: fnv1a32(encode(B.cr)), rd: fnv1a32(encode(B.rd)) });
const hex = h => '0x' + h.toString(16).padStart(8, '0');
export function blockLines(B) {
  const H = hashes(B);
  return [
    `// recipes v${RECIPE_V}: our own struck-plate models (IMPL-7c §2.4, §14 lane R9) · 6-bit words, one character each, code =`,
    `// ROM909_A.indexOf(character), mid-scale 32 · 30 kHz nominal · hh 32 768 words (open 0–24 575, closed 24 576–32 767), cr and`,
    `// rd 32 768 · FNV-1a hh ${hex(H.hh)} cr ${hex(H.cr)} rd ${hex(H.rd)} · cymbals pre-compensated by the ${B.env === 'model'
      ? "model's staircase (Dr808.proto.tr909.ENV9)" : "tool's stand-in staircase (placeholder: no ENV9 yet)"}`,
    `const ROM909_A = '${ALPHABET}';`,
    'const ROM909 = {',
    `  hh: '${encode(B.hh)}',`,
    `  cr: '${encode(B.cr)}',`,
    `  rd: '${encode(B.rd)}',`,
    '};',
  ];
}
// the frame: the start and end marker lines (each alone on its line, any indent); everything between is the tool's
export function frameOf(src) {
  const L = src.split('\n'), a = [], b = [];
  L.forEach((l, i) => { const t = l.trim(); if (t === MARK_A) a.push(i); else if (t === MARK_B) b.push(i); });
  if (!a.length || !b.length) return { err: 'the ROM909 frame is missing from dr-808.js (lane V9 adds the two marker lines: '
    + `"${MARK_A}" and "${MARK_B}"; then node tools/rom909.mjs --write)` };
  if (a.length > 1 || b.length > 1 || b[0] < a[0]) return { err: 'dr-808.js has a malformed ROM909 frame (one start marker, then one end marker)' };
  return { L, a: a[0], b: b[0], indent: L[a[0]].match(/^\s*/)[0] };
}
export function withBlock(src, B) {
  const F = frameOf(src);
  if (F.err) throw new Error('rom909: ' + F.err);
  return [...F.L.slice(0, F.a + 1), ...blockLines(B).map(l => F.indent + l), ...F.L.slice(F.b)].join('\n');
}
export function check(src, B) {
  const F = frameOf(src);
  if (F.err) return { ok: false, why: F.err };
  const want = blockLines(B).map(l => F.indent + l), got = F.L.slice(F.a + 1, F.b);
  if (got.length === want.length && got.every((l, i) => l === want[i])) return { ok: true, why: 'current' };
  return { ok: false, why: 'the ROM909 block in dr-808.js is stale or hand-edited (run node tools/rom909.mjs --write)' };
}

// ---------------------------------------------------------------- statistics (the designer's view; also the test's numbers)
// level in 5 ms windows (dB re the peak window), the −N dB times, the spectral centroid of a span (a 1024-point FFT, Hann)
export function levels(codes, a = 0, n = codes.length) {
  const y = new Float64Array(n);
  for (let i = 0; i < n; i++) y[i] = codes[a + i] - 32;
  return msOf(y);
}
function fft(re, im) {
  const n = re.length;
  for (let i = 1, j = 0; i < n; i++) {
    let bit = n >> 1;
    for (; j & bit; bit >>= 1) j ^= bit;
    j ^= bit;
    if (i < j) { let t = re[i]; re[i] = re[j]; re[j] = t; t = im[i]; im[i] = im[j]; im[j] = t; }
  }
  for (let len = 2; len <= n; len <<= 1) {
    const w = -TAU / len, wr = cosD(w), wi = sinD(w);
    for (let i = 0; i < n; i += len) {
      let cr = 1, ci = 0;
      for (let j = 0; j < len / 2; j++) {
        const a = i + j, b = a + len / 2, tr = re[b] * cr - im[b] * ci, ti = re[b] * ci + im[b] * cr;
        re[b] = re[a] - tr; im[b] = im[a] - ti; re[a] += tr; im[a] += ti;
        const t = cr * wr - ci * wi; ci = cr * wi + ci * wr; cr = t;
      }
    }
  }
}
// the power spectrum of codes[a … a + 1024) (mean removed, Hann): bins of 30000 / 1024 Hz
export function spectrum(codes, a, N = 1024) {
  const re = new Float64Array(N), im = new Float64Array(N);
  let m = 0;
  for (let i = 0; i < N; i++) m += codes[a + i];
  m /= N;
  for (let i = 0; i < N; i++) re[i] = (codes[a + i] - m) * 0.5 * (1 - cosD(TAU * i / N));
  fft(re, im);
  const p = new Float64Array(N / 2);
  for (let k = 0; k < N / 2; k++) p[k] = re[k] * re[k] + im[k] * im[k];
  return p;
}
export function centroid(codes, a, N = 1024) {
  const p = spectrum(codes, a, N);
  let s = 0, w = 0;
  for (let k = 1; k < N / 2; k++) { s += p[k]; w += p[k] * k * WORD_HZ / N; }
  return s > 0 ? w / s : 0;
}
export function stats(c, a, n) {
  const e = levels(c, a, n);
  let pk = 0, peak = 0, clip = 0, sum = 0;
  for (let i = 0; i < n; i++) {
    if (e[i] > e[pk]) pk = i;
    const v = c[a + i]; peak = Math.max(peak, Math.abs(v - 32)); if (v === 0 || v === 63) clip++; sum += v - 32;
  }
  const at = ms => e[Math.min(n - 1, Math.round(ms * WORD_HZ / 1000))];
  const t = db => { const k = e[pk] * dbA(2 * -db); let i = n - 1; while (i > pk && e[i] < k) i--; return (i + 1) / WORD_HZ; };
  const cen = [];
  for (let s = 0; s + 1024 <= n; s += 3000) cen.push(Math.round(centroid(c, a + s)));
  return { n, peak, clip, dc: sum / n, peakMs: pk / WORD_HZ * 1000, pkDb: dbOf(sqrtD(e[pk]) / 31.5),
    at300: n > 9000 ? 10 * logD(at(300) / e[pk]) / LN10 : null, t14: t(14), t20: t(20), t30: t(30), cen };
}
export function report(B) {
  const P = { oh: [B.hh, 0, OPEN_N], ch: [B.hh, OPEN_N, CLOSED_N], cr: [B.cr, 0, N_IMG], rd: [B.rd, 0, N_IMG] }, out = {};
  for (const [k, [c, a, n]] of Object.entries(P)) {
    const v = B.parts[k].v;
    let mg = 0.5;
    for (let i = 0; i < v.length; i++) mg = Math.min(mg, Math.abs(v[i] - Math.floor(v[i]) - 0.5));
    out[k] = Object.assign(stats(c, a, n), { margin: mg });
  }
  return out;
}


// phasor (a complex Gaussian: energy arriving later by the plate's nonlinear coupling, at a random phase).
// A strike: a stick's force pulse t·e^(−t/θ) (unit area; its spectrum 1 / (1 + (ωθ)²), no nulls) through every mode;
// amplitude tilt (f / 1 kHz)^β · f² / (f² + fl²) [/ (1 + (f / fh)²)]; damping σ(f) = σ0 + σ1 f + σ2 f² (s⁻¹, f in kHz: the

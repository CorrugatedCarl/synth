// ---------------------------------------------------------------- exactly specified maths (IEEE 754, round to nearest)
const PI = 3.141592653589793, HALF_PI = 1.5707963267948966, TAU = 6.283185307179586;
const LN2 = 0.6931471805599453, LN10 = 2.302585092994046, SQRT2 = 1.4142135623730951, SQRT3 = 1.7320508075688772;
export function expD(x) {                        // e^x: x = k ln2 + r, |r| ≤ ln2 / 2, Taylor to r²² (< 1e-24), × 2^k by halvings
  if (x < -700) return 0;
  const k = Math.round(x / LN2), r = x - k * LN2;
  let t = 1;
  for (let j = 22; j >= 1; j--) t = 1 + t * r / j;
  if (k > 0) for (let j = 0; j < k; j++) t *= 2; else for (let j = 0; j > k; j--) t *= 0.5;
  return t;
}
export function logD(x) {                        // ln x (x > 0): x = m 2^e, m ∈ [√½, √2], 2 atanh((m − 1) / (m + 1)) to s²⁵
  let e = 0;
  while (x >= 2) { x *= 0.5; e++; }
  while (x < 1) { x *= 2; e--; }
  if (x > SQRT2) { x *= 0.5; e++; }
  const s = (x - 1) / (x + 1), s2 = s * s;
  let t = 0;
  for (let j = 25; j >= 1; j -= 2) t = 1 / j + s2 * t;
  return e * LN2 + 2 * s * t;
}
const powD = (x, y) => expD(y * logD(x));
const dbA = db => expD(db * LN10 / 20);          // dB → amplitude
const dbOf = a => 20 * logD(a) / LN10;           // amplitude (> 0) → dB
function sinP(r) { const r2 = r * r; let t = 1; for (let j = 18; j >= 2; j -= 2) t = 1 - t * r2 / (j * (j + 1)); return r * t; }
function cosP(r) { const r2 = r * r; let t = 1; for (let j = 18; j >= 2; j -= 2) t = 1 - t * r2 / ((j - 1) * j); return t; }
function sc(x, q0) {                             // sin (q0 0) or cos (q0 1) by quadrant: |r| ≤ π/4
  const k = Math.round(x / HALF_PI), r = x - k * HALF_PI, q = (((k + q0) % 4) + 4) % 4;
  return q === 0 ? sinP(r) : q === 1 ? cosP(r) : q === 2 ? -sinP(r) : -cosP(r);
}
export const sinD = x => sc(x, 0), cosD = x => sc(x, 1);

// the seeds (IMPL-7c §2.4: wt.js's generator): a uniform [0, 1) stream per name; gauss: Irwin–Hall of four, unit variance
export const rng = name => mulberry32(fnv1a32('rom909:' + name + ':' + RECIPE_V));
const gauss = rnd => (rnd() + rnd() + rnd() + rnd() - 2) * SQRT3;

